#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Calamares job: write optional repository choices into the target.

The packagechooser page is a view module; this job consumes its Global Storage
value and performs the only privileged file changes. The actual package
installation (archlinuxcn-keyring) happens later, inside the post-install
arch-chroot script, so failures can be handled without aborting Calamares.
"""

import os
import shutil
from pathlib import Path

import libcalamares


def pretty_name():
    return "Configure optional repositories"


def _as_list(value):
    if value is None:
        return []
    if isinstance(value, (list, tuple)):
        return [str(v).strip() for v in value if str(v).strip()]
    return [part.strip() for part in str(value).split(",") if part.strip()]


def _write(path: Path, content: str):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")
    os.chmod(path, 0o644)


def run():
    target = libcalamares.globalstorage.value("rootMountPoint")
    if not target:
        libcalamares.utils.warning("stardustarch_options: rootMountPoint is unset")
        return None

    root = Path(str(target))
    etc = root / "etc"
    if str(root) == "/" or not etc.is_dir():
        libcalamares.utils.warning("stardustarch_options: refusing unsafe target root")
        return None

    selected = _as_list(libcalamares.globalstorage.value("packagechooser_repos"))
    configuration = libcalamares.job.configuration or {}
    log_dir = root / "etc" / "stardustarch"
    log_dir.mkdir(parents=True, exist_ok=True)

    if "china-mirrors" in selected:
        mirrors = configuration.get("china_mirrors") or []
        if mirrors:
            mirrorlist = etc / "pacman.d" / "mirrorlist"
            backup = etc / "pacman.d" / "mirrorlist.stardustarch-original"
            try:
                if mirrorlist.exists() and not backup.exists():
                    shutil.copy2(mirrorlist, backup)
                body = [
                    "# Generated by StardustArch Calamares.",
                    "# The original Arch mirrorlist is saved as",
                    "# /etc/pacman.d/mirrorlist.stardustarch-original",
                    "",
                ]
                body.extend("Server = {}".format(str(url)) for url in mirrors)
                _write(mirrorlist, "\n".join(body) + "\n")
                libcalamares.utils.debug("stardustarch_options: China mirrors written")
            except OSError as exc:
                libcalamares.utils.warning(
                    "stardustarch_options: could not write mirrorlist: {}".format(exc)
                )

    if "archlinuxcn" in selected:
        repo = etc / "pacman.d" / "stardustarch-archlinuxcn.conf"
        server = (configuration.get("archlinuxcn") or {}).get(
            "server", "https://repo.archlinuxcn.org/$arch"
        )
        include = "Include = /etc/pacman.d/stardustarch-archlinuxcn.conf"
        try:
            _write(
                repo,
                "# StardustArch optional repository; enabled at install time.\n"
                "# This temporary SigLevel is tightened by post-install-syu.sh\n"
                "# after archlinuxcn-keyring has been installed and populated.\n"
                "[archlinuxcn]\n"
                "SigLevel = Optional TrustAll\n"
                "Server = {}\n".format(server),
            )
            pacman_conf = etc / "pacman.conf"
            text = pacman_conf.read_text(encoding="utf-8")
            if include not in text:
                with pacman_conf.open("a", encoding="utf-8") as handle:
                    handle.write(
                        "\n# Added by StardustArch Calamares (optional).\n"
                        "{}\n".format(include)
                    )
            libcalamares.utils.debug("stardustarch_options: archlinuxcn enabled")
        except OSError as exc:
            libcalamares.utils.warning(
                "stardustarch_options: could not configure archlinuxcn: {}".format(exc)
            )

    options = log_dir / "install-options.conf"
    try:
        _write(
            options,
            "CHINA_MIRRORS={}\nARCHLINUXCN={}\n".format(
                1 if "china-mirrors" in selected else 0,
                1 if "archlinuxcn" in selected else 0,
            ),
        )
    except OSError as exc:
        libcalamares.utils.warning(
            "stardustarch_options: could not write install options: {}".format(exc)
        )

    libcalamares.globalstorage.insert(
        "stardustarch_repo_choices", ",".join(selected)
    )
    return None
